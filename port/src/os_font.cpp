bool loadOsFont(const std::string &path, uint8_t font[kOsFontBytes]) {
	FILE *f = std::fopen(path.c_str(), "rb");
	if (!f) return false;
	std::vector<uint8_t> data;
	uint8_t buf[4096];
	for (size_t n; (n = std::fread(buf, 1, sizeof buf, f)) > 0;) data.insert(data.end(), buf, buf + n);
	std::fclose(f);
	size_t offset;
	if (data.size() == 10240) offset = 0xE000 - 0xD800;        // OS-B, $D800-$FFFF
	else if (data.size() == 16384) offset = 0xE000 - 0xC000;   // XL/XE, $C000-$FFFF
	else if (data.size() == size_t(kOsFontBytes)) offset = 0;
	else return false;
	std::memcpy(font, data.data() + offset, kOsFontBytes);
	return true;
}

void builtinOsFont(uint8_t font[kOsFontBytes]) {
	std::memset(font, 0, kOsFontBytes);
	for (const Glyph &g : kGlyphs) {
		for (int row = 0; row < 8; row++) {
			uint8_t bits = 0;
			for (int x = 0; x < 8; x++)
				if (g.rows[row][x] == '#') bits |= uint8_t(0x80 >> x);
			font[g.code * 8 + row] = bits;
		}
	}
}

